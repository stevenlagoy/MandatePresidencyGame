package com.stevenlagoy.presidency.characters.attributes.experiences

enum class ExperienceTier {
    /** Entry-level position requiring limited prior experience and open to any working age. */
    ENTRY,
    /** Mid-level position requiring some prior applied experience and generally open to those over 22 years old. */
    MID,
    /** High-level position requiring extensive knowledge and experience in the field and open to those over 28 years old. */
    HIGH,
    /** Terminal-level position with huge impact on industry or government, requiring unsurpassed experience and open to those over 32 years old. */
    TERMINAL,
}
